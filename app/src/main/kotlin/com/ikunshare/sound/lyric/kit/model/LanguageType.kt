    ChineseSimplified("zh-hans"),
    ChineseTraditional("zh-hant"),
    English("en"),
    Japanese("ja"),
    Korean("ko"),
    Russian("ru"),
    French("fr"),
    German("de"),
    Spanish("es"),
    Italian("it"),
    Portuguese("pt"),
}
